"""Build stimuli.js (and lists.csv for documentation) from translations.csv.

Design
------
- 60 images (12 per category x 5 categories) are split into two halves of 30,
  6 per category in each half (fixed seed, so it is reproducible).
- Within a half, images are ordered by category, and the translation variant is
  rotated: image j in rotation r gets variant (j + r) % 3. That gives 3 lists per
  half -> 6 lists total. Each list has 30 trials: 10 per variant, and 2 per
  variant per category.
- Across the 6 lists every one of the 180 (image, variant) pairs appears exactly
  once, so 6 participants per list (36 total) gives exactly 6 judgments per pair.
- Each list also gets 3 attention-check images taken from the OTHER half, so a
  participant never sees one of their own trial images twice.

Usage:
    python3 tools/build_stimuli.py [path/to/translations.csv]
"""

import csv
import json
import random
import sys
from collections import defaultdict
from pathlib import Path

APP_DIR = Path(__file__).resolve().parent.parent
DEFAULT_CSV = APP_DIR.parent / "study_samples" / "translations.csv"
SEED = 20261123
VARIANTS = ["ver1_es", "ver2_ja", "ver3_es_ja"]
N_ATTENTION = 3


def main():
    csv_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_CSV
    rows = list(csv.DictReader(open(csv_path, encoding="utf-8")))

    for r in rows:
        for col in ["original"] + VARIANTS:
            if not r[col].strip():
                sys.exit(f"Empty {col} for image {r['image_id']}")
        if not (APP_DIR / "images" / f"{r['image_id']}.jpg").exists():
            sys.exit(f"Missing image file images/{r['image_id']}.jpg")

    by_cat = defaultdict(list)
    for r in rows:
        by_cat[r["category"]].append(r)

    rng = random.Random(SEED)
    halves = [[], []]
    for cat in sorted(by_cat):
        items = sorted(by_cat[cat], key=lambda r: r["image_id"])
        if len(items) % 2:
            sys.exit(f"Category {cat} has an odd number of images ({len(items)})")
        rng.shuffle(items)
        k = len(items) // 2
        halves[0] += sorted(items[:k], key=lambda r: r["image_id"])
        halves[1] += sorted(items[k:], key=lambda r: r["image_id"])
    # halves are already grouped by category (categories added in sorted order)

    images = {
        r["image_id"]: {
            "image_id": r["image_id"],
            "category": r["category"],
            "file": f"images/{r['image_id']}.jpg",
            "original": r["original"].strip(),
            **{v: r[v].strip() for v in VARIANTS},
        }
        for r in rows
    }

    lists = []
    for h, half in enumerate(halves):
        other = halves[1 - h]
        # attention-check images: one from each of the first N categories of the other half
        seen_cats, att = set(), []
        for r in other:
            if r["category"] not in seen_cats and len(att) < N_ATTENTION:
                att.append(r["image_id"])
                seen_cats.add(r["category"])
        for rot in range(3):
            trials = [
                {"image_id": r["image_id"], "variant": VARIANTS[(j + rot) % 3]}
                for j, r in enumerate(half)
            ]
            lists.append({
                "list_id": h * 3 + rot + 1,  # 1..6
                "half": "A" if h == 0 else "B",
                "rotation": rot,
                "trials": trials,
                "attention_images": att,
            })

    # sanity checks
    pairs = [(t["image_id"], t["variant"]) for L in lists for t in L["trials"]]
    assert len(pairs) == len(set(pairs)) == len(rows) * 3, "pairs not covered exactly once"
    for L in lists:
        counts = defaultdict(int)
        for t in L["trials"]:
            counts[t["variant"]] += 1
        assert set(counts.values()) == {len(L["trials"]) // 3}, f"unbalanced list {L['list_id']}"

    out = APP_DIR / "stimuli.js"
    out.write_text(
        "// AUTO-GENERATED by tools/build_stimuli.py. Do not edit by hand.\n"
        f"const IMAGES = {json.dumps(images, indent=1, ensure_ascii=False)};\n"
        f"const LISTS = {json.dumps(lists, indent=1)};\n",
        encoding="utf-8",
    )

    with open(APP_DIR / "tools" / "lists.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["list_id", "half", "image_id", "category", "variant", "role"])
        for L in lists:
            for t in L["trials"]:
                w.writerow([L["list_id"], L["half"], t["image_id"], images[t["image_id"]]["category"], t["variant"], "trial"])
            for a in L["attention_images"]:
                w.writerow([L["list_id"], L["half"], a, images[a]["category"], "", "attention_check"])

    print(f"Wrote {out} ({len(lists)} lists x {len(lists[0]['trials'])} trials + {N_ATTENTION} attention checks)")


if __name__ == "__main__":
    main()
